"""Generate WebP delivery assets from preserved PNG originals (requires Pillow)."""
from pathlib import Path
from hashlib import sha256
import json
from PIL import Image, ImageOps

root = Path(__file__).resolve().parent.parent
assets = root / 'public/assets'
output = assets / 'optimized'
output.mkdir(exist_ok=True)
variants = {}
original_bytes = full_bytes = thumb_bytes = 0
for source in sorted(assets.rglob('*.png')):
    if output in source.parents:
        continue
    url = '/' + source.relative_to(root / 'public').as_posix()
    image = ImageOps.exif_transpose(Image.open(source)).convert('RGBA')
    if source.name == 'fundo site.png':
        image.thumbnail((1920, 1920), Image.Resampling.LANCZOS)
    def encode(im, suffix):
        import io
        buf = io.BytesIO()
        im.save(buf, format='WEBP', quality=85, method=4)
        data = buf.getvalue()
        name = f'{sha256(url.encode()).hexdigest()[:12]}{suffix}.{sha256(data).hexdigest()[:12]}.webp'
        target = output / name
        if not target.exists():
            target.write_bytes(data)
        return '/assets/optimized/' + name, len(data)
    full, size = encode(image, '')
    original_bytes += source.stat().st_size
    full_bytes += size
    variant = {'full': full, 'width': image.width}
    if source.parent.name == 'Cards':
        thumb = image.copy()
        thumb.thumbnail((320, 480), Image.Resampling.LANCZOS)
        variant['thumb'], size = encode(thumb, '-thumb')
        variant['thumbWidth'] = thumb.width
        thumb_bytes += size
    variants[url] = variant
module = '''// Generated by scripts/optimize-images.py; PNG originals remain the fallback.
const variants = VARIANTS;
export function optimizedImageUrl(url) {
  return variants[url]?.full || url;
}
export function setImageSource(image, url, thumbnail = false) {
  image.src = url;
  optimizeImage(image, thumbnail);
}
export function optimizeImage(image, thumbnail = false) {
  const variant = variants[image.getAttribute("src")];
  image.decoding = "async";
  if (!variant) {
    image.removeAttribute("srcset");
    image.removeAttribute("sizes");
    return;
  }
  if (thumbnail && variant.thumb) {
    image.srcset = `${variant.thumb} ${variant.thumbWidth}w, ${variant.full} ${variant.width}w`;
    image.sizes = "(max-width: 600px) 40vw, 220px";
  } else {
    image.srcset = variant.full;
    image.removeAttribute("sizes");
  }
}
'''.replace('VARIANTS', json.dumps(variants, ensure_ascii=False, indent=2))
(root / 'public/JS/image-sources.js').write_text(module, encoding='utf-8')
# Keep the project's offline asset audit in sync with generated delivery files.
guide_path = root / 'GUIA_DO_PROJETO.txt'
guide = guide_path.read_text(encoding='utf-8')
start_marker = '[ARTES_WEBP_GERADAS_INICIO]'
end_marker = '[ARTES_WEBP_GERADAS_FIM]'
if start_marker in guide and end_marker in guide:
    before, rest = guide.split(start_marker, 1)
    _, after = rest.split(end_marker, 1)
    entries = '\n'.join('- ' + p.relative_to(root).as_posix() + ' — Variante WebP versionada gerada da arte PNG.' for p in sorted(output.glob('*.webp')))
    guide_path.write_text(before + start_marker + '\n' + entries + '\n' + end_marker + after, encoding='utf-8')
print(json.dumps({'images':len(variants),'originalBytes':original_bytes,'webpBytes':full_bytes,'thumbnailBytes':thumb_bytes}))
